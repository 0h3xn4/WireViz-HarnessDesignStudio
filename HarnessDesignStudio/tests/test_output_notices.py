"""D-210 (brief 2.4): every written document carries the notice, in every format, and the pending
and placeholder values stay marked.

The notice is `texts.md` OUTPUT_NOTICE: the tool, its version, "Provided as is, without warranty.
Verify before use." Where each format carries it:

- .csv and .yaml: a second comment line under the stamp line;
- .md reports: a note line under the stamp comment;
- .xlsx: the row "Notice" of the sheet About, the description of the file and (the build
  workbook) the print footer and the status line under its title (no row is added);
- .svg and .pdf drawings: a line of the title block or under the title of a system sheet, and the
  description of the file;
- .json and the open data (formats that cannot hold a comment): the file README.txt of the folder.
"""

import io
import re
from collections.abc import Iterator
from pathlib import Path

import pytest

from harness_design_studio import __version__
from harness_design_studio.core import legal_texts
from harness_design_studio.core.generate.engine import generate_project
from harness_design_studio.core.outputs.build import build_outputs
from harness_design_studio.core.outputs.stamp import parse_csv, stamp_of
from harness_design_studio.core.outputs.verify import verify_outputs
from harness_design_studio.core.outputs.xlsx_env import load_workbook
from harness_design_studio.core.samples import mini3

NOTICE = legal_texts.output_notice("harness-design-studio", __version__)


@pytest.fixture(scope="module")
def files() -> dict[str, bytes]:
    project = mini3()
    generate_project(project)
    built = build_outputs(project)
    assert verify_outputs(project, built.files).ok  # the self-check reads every file back
    return built.files


def _of(files: dict[str, bytes], suffix: str) -> Iterator[tuple[str, bytes]]:
    found = [(rel, data) for rel, data in sorted(files.items()) if rel.endswith(suffix)]
    assert found, f"no {suffix} file"
    return iter(found)


def test_the_notice_is_the_one_in_the_source() -> None:
    assert (
        f"harness-design-studio {__version__}. Provided as is, without warranty. Verify before use."
        == NOTICE
    )
    assert stamp_of(mini3()).notice == NOTICE


def test_every_csv_has_the_notice_under_the_stamp_and_reads_back(files: dict[str, bytes]) -> None:
    for rel, data in _of(files, ".csv"):
        lines = data.decode().split("\n")
        assert lines[0].startswith("# harness-design-studio ") and " model " in lines[0], rel
        assert lines[1] == f"# {NOTICE}", rel
        assert all(not row[0].startswith("# ") for row in parse_csv(data)[:1]), rel


def test_every_yaml_has_the_notice_under_the_stamp(files: dict[str, bytes]) -> None:
    for rel, data in _of(files, ".yaml"):
        assert data.decode().split("\n")[1] == f"# {NOTICE}", rel


def test_every_markdown_report_has_the_notice_as_a_visible_note(files: dict[str, bytes]) -> None:
    for rel, data in _of(files, ".md"):
        lines = data.decode().split("\n")
        assert lines[0].startswith("<!-- harness-design-studio "), rel
        assert lines[1] == f"> {NOTICE}", rel


def test_every_workbook_has_the_notice_on_its_about_sheet_and_in_its_properties(
    files: dict[str, bytes],
) -> None:
    for rel, data in _of(files, ".xlsx"):
        wb = load_workbook(io.BytesIO(data))
        rows = [[c for c in row] for row in wb["About"].iter_rows(values_only=True)]
        assert ["Notice", NOTICE] in rows, rel
        assert rows[0][0] == "Generated by" and rows[1][0] == "Model hash", (
            rel
        )  # the verifier's rows
        assert wb.properties.description == NOTICE, rel


def test_the_build_workbook_shows_the_notice_under_its_title_and_in_the_print_footer(
    files: dict[str, bytes],
) -> None:
    rel = next(r for r in files if r.endswith("_build.xlsx"))
    wb = load_workbook(io.BytesIO(files[rel]))
    texts = [str(c) for ws in wb for row in ws.iter_rows(values_only=True) for c in row if c]
    assert any(NOTICE in t and "status " in t for t in texts)  # beside the status of the harness
    assert any(NOTICE in (ws.oddFooter.left.text or "") for ws in wb if ws.title != "About")


def test_every_svg_and_pdf_drawing_shows_the_notice(files: dict[str, bytes]) -> None:
    for rel, data in _of(files, ".svg"):
        text = data.decode()
        assert NOTICE in re.sub(r"<[^>]*>", "\n", text), f"{rel}: the notice is not drawn"
        assert (
            f"<desc>harness-design-studio {__version__} model" in text
            and NOTICE in text.split("</desc>")[0]
        ), rel
    for rel, data in _of(files, ".pdf"):
        assert b"Provided as is, without warranty" in data, rel


def test_the_json_files_and_the_open_data_have_the_notice_in_the_readme_of_the_folder(
    files: dict[str, bytes],
) -> None:
    readme = files["README.txt"].decode()
    assert (
        NOTICE in readme and legal_texts.DISCLAIMER in readme and legal_texts.INTENDED_USE in readme
    )
    assert "system/export.json" in readme and "system/provenance.json" in readme
    assert any(rel.endswith(".json") for rel in files)


# ---- pending and placeholder values stay marked, in every format ---------------------------------


def test_csv_marks_pending_values(files: dict[str, bytes]) -> None:
    wires = files["harnesses/W001/wirelist.csv"].decode()
    assert ",pending," in wires  # the wire size is not chosen: it says so
    assert "pending (example data)" in files["harnesses/W001/bom.csv"].decode()
    mass = files["harnesses/W001/mass_length.csv"].decode()
    assert ",no," in mass and "Missing data" in mass  # not complete, and what is missing


def test_markdown_marks_example_data_and_what_was_not_checked(files: dict[str, bytes]) -> None:
    report = files["system/drc_report.md"].decode()
    assert "(example data)" in report
    assert re.search(r"not checked|pending|placeholder", report, re.IGNORECASE)


def test_json_marks_pending_approval_and_the_placeholder_files(files: dict[str, bytes]) -> None:
    export = files["system/export.json"].decode()
    assert '"approval": "pending"' in export
    assert "placeholder" in files["system/provenance.json"].decode().lower()


def test_drawings_mark_pending_and_example_data(files: dict[str, bytes]) -> None:
    svg = files["harnesses/W001/drawing_A3_s1.svg"].decode()
    assert "pending" in svg and "(example data)" in svg
    assert b"pending" in files["harnesses/W001/drawing_A4.pdf"]


def test_workbooks_mark_pending_values(files: dict[str, bytes]) -> None:
    wb = load_workbook(io.BytesIO(files["harnesses/W001/W001.xlsx"]))
    cells = [str(c) for ws in wb for row in ws.iter_rows(values_only=True) for c in row if c]
    assert "pending" in cells
    build = load_workbook(io.BytesIO(files["harnesses/W001/W001_build.xlsx"]))
    texts = " ".join(
        str(c) for ws in build for row in ws.iter_rows(values_only=True) for c in row if c
    )
    assert re.search(r"pending|not checked|placeholder|TBD", texts, re.IGNORECASE)


def test_the_wireviz_yaml_carries_no_electrical_value_it_could_leave_unmarked(
    files: dict[str, bytes],
) -> None:
    """The WireViz-style file holds the connection structure only. A wire size or a part that is
    pending is left out, never filled in with a number of the tool."""
    yaml = files["harnesses/W001/wireviz.yaml"].decode()
    assert "gauge" not in yaml and "awg" not in yaml.lower()
    assert yaml.split("\n")[1] == f"# {NOTICE}"


def test_the_readme_of_the_folder_names_the_markers(files: dict[str, bytes]) -> None:
    readme = files["README.txt"].decode()
    for marker in ("pending", "(example data)", "PLACEHOLDER", "Complete: no", "not checked"):
        assert marker in readme


def test_a_written_folder_holds_the_readme_and_it_is_listed_in_the_manifest(tmp_path: Path) -> None:
    from harness_design_studio.core.outputs.build import write_outputs

    project = mini3()
    generate_project(project)
    write_outputs(project, tmp_path / "out")
    assert (tmp_path / "out" / "README.txt").read_text().startswith("Harness Design Studio")
    manifest = (tmp_path / "out" / "manifest.json").read_text()
    assert '"README.txt"' in manifest
